-- Private schema: never add kienhoc to the Supabase Data API exposed schemas.
CREATE SCHEMA IF NOT EXISTS kienhoc;
REVOKE ALL ON SCHEMA kienhoc FROM PUBLIC;
CREATE TABLE IF NOT EXISTS kienhoc.users (
  id TEXT PRIMARY KEY, email TEXT UNIQUE NOT NULL,
  password_hash TEXT, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS kienhoc.otps (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL, code TEXT NOT NULL, expires_at BIGINT NOT NULL,
  used INTEGER NOT NULL DEFAULT 0 CHECK (used IN (0,1)),
  attempts INTEGER NOT NULL DEFAULT 0, created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS otps_email ON kienhoc.otps(email,id DESC);
CREATE TABLE IF NOT EXISTS kienhoc.progress (
  user_id TEXT PRIMARY KEY REFERENCES kienhoc.users(id) ON DELETE CASCADE,
  data TEXT NOT NULL CHECK (jsonb_typeof(data::jsonb) = 'object'),
  updated_at TEXT NOT NULL, revision INTEGER NOT NULL DEFAULT 1 CHECK (revision >= 1)
);
CREATE TABLE IF NOT EXISTS kienhoc.sessions (
  id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES kienhoc.users(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user ON kienhoc.sessions(user_id);
CREATE INDEX IF NOT EXISTS sessions_expiry ON kienhoc.sessions(expires_at);
ALTER TABLE kienhoc.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE kienhoc.otps ENABLE ROW LEVEL SECURITY;
ALTER TABLE kienhoc.progress ENABLE ROW LEVEL SECURITY;
ALTER TABLE kienhoc.sessions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA kienhoc FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA kienhoc FROM PUBLIC;
-- No anon/authenticated policies: access is exclusively through the backend.
